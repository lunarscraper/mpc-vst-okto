/* ---- MIDI ------------------------------------------------------------------ */
static void midi(Plugin *w, const uint8_t *d) {
    const int st = d[0] & 0xf0, n = d[1] & 0x7f, v = d[2] & 0x7f;
    if (st == 0x90 && v > 0) w->engine.note_on(n, v);
    else if (st == 0x80 || st == 0x90) w->engine.note_off(n);
    else if (st == 0xe0) w->engine.set_bend(((v << 7 | n) - 8192) / 8192.0f);
    else if (st == 0xb0 && n == 1) w->engine.set_wheel(v / 127.0f);
    else if (st == 0xb0 && n == 64) w->engine.set_sustain(v >= 64);
    else if (st == 0xb0 && n == 120) w->engine.all_off();
    else if (st == 0xb0 && n == 123) w->engine.all_release();
}

static void processReplacing(AEffect *e, float **in, float **out, int32_t n) {
    (void)in;
    Plugin *w = (Plugin *)e->object;
    NoDenormals nd;
    flush_pend0(w);
    if (w->dirty.exchange(false)) configure(w);
    float *L = out[0], *R = out[1];
    std::memset(L, 0, sizeof(float) * (size_t)n);
    std::memset(R, 0, sizeof(float) * (size_t)n);

    const VstTimeInfo *ti = (const VstTimeInfo *)w->master(&w->fx, audioMasterGetTime, 0, kVstTempoValid, 0, 0.0f);
    if (ti && (ti->flags & kVstTempoValid)) w->engine.set_tempo(ti->tempo);

    int pos = 0, k = 0;
    while (pos < n) {
        while (k < w->nev && w->ev[k].frame <= pos) midi(w, w->ev[k++].d);
        int f = n;
        if (k < w->nev) f = clampi(w->ev[k].frame, pos + 1, n);
        w->engine.render(L + pos, R + pos, f - pos);
        pos = f;
    }
    while (k < w->nev) midi(w, w->ev[k++].d);
    w->nev = 0;

    for (int c = 0; c < 2; c++) {
        float *y = out[c];
        for (int i = 0; i < n; i++) {
            const float a = std::fabs(y[i]);              /* output safety above -3 dBFS, ceiling 0.98 */
            if (a > 0.7f) {
                float t = std::min((a - 0.7f) / 0.3f, 3.0f), t2 = t * t;
                y[i] = std::copysign(0.7f + 0.28f * t * (27 + t2) / (27 + 9 * t2), y[i]);
            }
        }
    }
    bool any = false;
    for (int i = 0; i < NPARAMS; i++) {
        /* a trigger reports itself released (the Force sends no setParameter(0) after a tap) */
        if (w->release[i]) { w->release[i] = 0; w->down[i] = false; any = true; w->master(&w->fx, audioMasterAutomate, i, 0, 0, 0.0f); }
        if (!w->notify[i].exchange(0)) continue;
        any = true;
        w->master(&w->fx, audioMasterAutomate, i, 0, 0, norm_of(w, i));
    }
    if (any) w->need_update.store(true);
    /* at most one UpdateDisplay per 50 ms; a request inside that window waits, it is not dropped */
    if (w->update_wait > 0) w->update_wait -= n;
    if (w->update_wait <= 0 && w->need_update.exchange(false)) {
        w->update_wait = (int)(w->sr * 0.05f);
        w->master(&w->fx, audioMasterUpdateDisplay, 0, 0, 0, 0.0f);
    }
}

static intptr_t process_events(Plugin *w, const VstEvents *evs) {
    if (!evs) return 0;
    for (int i = 0; i < evs->numEvents; i++) {
        const VstEvent *ev = evs->events[i];
        if (!ev || ev->type != kVstMidiType || w->nev >= MAXEV) continue;
        const VstMidiEvent *m = (const VstMidiEvent *)ev;
        MidiEv &q = w->ev[w->nev++];
        q.frame = m->deltaFrames;
        q.d[0] = m->midiData[0]; q.d[1] = m->midiData[1]; q.d[2] = m->midiData[2];
    }
    std::stable_sort(w->ev, w->ev + w->nev, [](const MidiEv &a, const MidiEv &b) { return a.frame < b.frame; });
    return 1;
}

static void set_param_now(Plugin *w, int32_t i, float n) {
    if (i < 0 || i >= NPARAMS) return;
    const param_t *p = &PARAMS[i];
    if (popup_set(w->open, i, n)) { if (w->open[i] > 0.5f) popup_close_others(w->open, w->release, i); return; }
    const int key = KEY_OF[i];
    if (key < 0) return;
    if (key == K_SLOT) {   /* browsing only: LOAD loads, so turning the knob can't wipe what is playing */
        const int v = (int)std::lround(clamp01(n) * (NSLOTS - 1));
        if (v != w->cur.load()) { w->cur.store(v); w->need_update.store(true); }   /* the slot's name is shown */
        return;
    }
    if (is_trigger(key)) {
        const bool down = n > 0.5f;
        const bool rising = down && !w->down[i];   /* an echo of our own automate must not fire again */
        w->down[i] = down;
        if (rising) {
            if (key == K_LOAD) slot_load(w);
            else slot_save(w);
            w->release[i] = 1;
            w->need_update.store(true);
        }
        return;
    }
    int t = i;                         /* where the value goes: an edit knob writes the operator's parameter */
    if (is_proxy(key)) { t = proxy_target(w, key); if (t < 0) return; }
    bool nudge = false;
    if (p->nopts > 1) {                /* a Q-Link event or a wheel click lands between two options: settled to a step */
        const float pos = clamp01(n) * (p->nopts - 1), cur = w->cache[t].load() * (p->nopts - 1);
        nudge = std::fabs(pos - std::round(pos)) > 0.001f;
        const float idx = settle(pos, cur, w->last_pos[i]);
        w->last_pos[i] = pos;
        n = (float)clampi((int)idx, 0, p->nopts - 1) / (p->nopts - 1);
    }
    const float before = w->cache[t].load();
    w->cache[t].store(clamp01(n));
    w->dirty.store(true);
    if (key == K_SEL && before != w->cache[t].load()) {   /* another operator: every edit knob reads anew */
        for (int k = X_OP0; k < G0; k++) if (IDX[k] >= 0) { w->notify[IDX[k]].store(1); w->last_pos[IDX[k]] = -1; }
        w->need_update.store(true);    /* like the wrapper's "refresh_display": the values shown change */
    }
    /* No UpdateDisplay for a plain host write (mpc-vst-plugins NOTES 2026-10-21): MPC rebuilds its parameter
     * screen on each one, which left Q-Links unable to move a param on the automation screen. */
    if (!nudge) popup_picked(w->open, w->release, i);
}
/* MPC's host sets parameter 0 (here EDIT) to the far end and straight back on insert and on every STOP
 * (mpc-vst-plugins NOTES 2026-10-10). So a host set of parameter 0 waits for the next block, a read or another
 * set; only the last one counts, and a pair that ends where it started is dropped. */
static void flush_pend0(Plugin *w) {
    if (!w->has_pend0.exchange(false)) return;
    if (std::fabs(w->pend0 - w->pend0_from) > 1e-6f) set_param_now(w, 0, w->pend0);
}
static void setParameter(AEffect *e, int32_t i, float n) {
    Plugin *w = (Plugin *)e->object;
    if (i == 0) {
        if (!w->has_pend0.load()) w->pend0_from = w->cache[0].load();
        w->pend0 = n;
        w->has_pend0.store(true);
        return;
    }
    flush_pend0(w);
    set_param_now(w, i, n);
}
static float getParameter(AEffect *e, int32_t i) {
    Plugin *w = (Plugin *)e->object;
    if (i < 0 || i >= NPARAMS) return 0.0f;
    flush_pend0(w);
    return norm_of(w, i);
}

/* project chunk: "OKTO1;" + the state + "prog=<slot>;" */
static intptr_t get_chunk(Plugin *w, void **ptr) {
    std::string t = "OKTO1;" + build_state(w, true);
    char buf[24];
    std::snprintf(buf, sizeof buf, "prog=%d;", w->cur.load());
    t += buf;
    w->chunk.assign(t.begin(), t.end());
    *ptr = w->chunk.data();
    return (intptr_t)w->chunk.size();
}
static intptr_t set_chunk(Plugin *w, const void *data, intptr_t len) {
    if (!data || len < 6) return 0;
    std::string t((const char *)data, (size_t)len);
    t.resize(std::strlen(t.c_str()));
    if (t.compare(0, 6, "OKTO1;")) return 0;
    start_values(w);
    ui_defaults(w);
    apply_state(w, t.substr(6), true);
    return 1;
}

/* ---- the value display ------------------------------------------------------ */
static void fmt_time(char *b, size_t n, float s) {
    if (s < 0.0015f) std::snprintf(b, n, "%.1f ms", s * 1000);
    else if (s < 1) std::snprintf(b, n, "%.0f ms", s * 1000);
    else std::snprintf(b, n, "%.2f s", s);
}
static void fmt_hz(char *b, size_t n, float hz) {
    if (std::fabs(hz) >= 1000) std::snprintf(b, n, "%.2f kHz", hz / 1000);
    else if (std::fabs(hz) >= 100) std::snprintf(b, n, "%.0f Hz", hz);
    else if (std::fabs(hz) >= 1) std::snprintf(b, n, "%.1f Hz", hz);
    else std::snprintf(b, n, "%.2f Hz", hz);
}
static void fmt_cents(char *b, size_t n, float depth) { std::snprintf(b, n, "%.0f ct", 1200 * std::log2(1 + depth)); }
static void fmt_pct(char *b, size_t n, float v) { std::snprintf(b, n, "%.0f %%", v); }

/* an envelope field e of the envelope whose E_EMODE key is base */
static void fmt_env(Plugin *w, int base, int e, float v, char *b, size_t n) {
    if (e == E_EREL) { fmt_time(b, n, law_time(v * 0.01f)); return; }
    if (e >= E_L1 && e <= E_L8) { std::snprintf(b, n, base == PE0 ? "%+.0f" : "%.0f", v); return; }
    if (e >= E_T1 && e <= E_T8) {
        const int s = clampi(ival(w, base + E_ESYNC), 0, 9);
        if (s) std::snprintf(b, n, "%d x %s", units_of(v), ESYNC_NAME[s]);
        else fmt_time(b, n, law_time(v * 0.01f));
        return;
    }
    fmt_pct(b, n, v);
}
static void display_key(Plugin *w, int idx, char *buf, size_t n) {
    const param_t *pp = &PARAMS[idx];
    const int key = KEY_OF[idx];
    if (pp->nopts) { std::snprintf(buf, n, "%s", pp->opts[norm_to_ui(pp, w->cache[idx].load())]); return; }
    const float v = val_at(w, idx);
    if (key >= OPR0 && key < MAT0) {
        const int f = (key - OPR0) % NOPALL, op = (key - OPR0) / NOPALL;
        if (f >= NOPF) { fmt_env(w, OPK(op, NOPF), f - NOPF, v, buf, n); return; }
        switch (f) {
        case F_FINE: std::snprintf(buf, n, "+%.3f", v * 0.01f); return;
        case F_OFFSET: { const float hz = law_offset(v * 0.01f); if (std::fabs(hz) < 0.005f) std::snprintf(buf, n, "0 Hz"); else { char t[24]; fmt_hz(t, sizeof t, std::fabs(hz)); std::snprintf(buf, n, "%s%s", hz < 0 ? "-" : "+", t); } return; }
        case F_LEVEL: if (v <= 0) std::snprintf(buf, n, "OFF"); else std::snprintf(buf, n, "x%.2f", law_level(v * 0.01f)); return;
        case F_PAN: if (std::fabs(v) < 0.5f) std::snprintf(buf, n, "C"); else std::snprintf(buf, n, "%s%.0f", v < 0 ? "L" : "R", std::fabs(v)); return;
        case F_KSLO: case F_KSHI: std::snprintf(buf, n, "%+.2f", v * 0.02f); return;
        case F_PM: fmt_cents(buf, n, law_pm(v * 0.01f)); return;
        default: fmt_pct(buf, n, v); return;
        }
    }
    if (key >= PE0) { fmt_env(w, PE0, key - PE0, v, buf, n); return; }
    switch (key) {
    case G_ENV_TIME: case G_REL_SCALE: std::snprintf(buf, n, "x%.2f", law_scale(v * 0.01f)); return;
    case G_LFO_RATE: fmt_hz(buf, n, law_lfo(v * 0.01f)); return;
    case G_LFO_DELAY: fmt_time(buf, n, 5.0f * sq(v * 0.01f)); return;
    case G_VIBRATO: case G_MW_VIB: fmt_cents(buf, n, law_pm(v * 0.01f)); return;
    case G_GLIDE: if (v <= 0) std::snprintf(buf, n, "OFF"); else fmt_time(buf, n, law_glide(v * 0.01f)); return;
    case G_DETUNE: std::snprintf(buf, n, "%.0f ct", v); return;
    case G_PE_DEPTH: std::snprintf(buf, n, "%.0f st", v); return;
    default: fmt_pct(buf, n, v); return;
    }
}
static void display(Plugin *w, int idx, char *buf, size_t n) {
    const param_t *pp = &PARAMS[idx];
    const int key = KEY_OF[idx];
    if (key == K_SLOT) { std::snprintf(buf, n, "%s", slot_title(clampi(w->cur.load(), 0, NSLOTS - 1)).c_str()); return; }
    if (key >= 0 && is_trigger(key)) { buf[0] = 0; return; }
    if (popup_is(idx)) {
        const int u = norm_to_ui(pp, w->open[idx]);
        if (pp->nopts) std::snprintf(buf, n, "%s", pp->opts[u]); else std::snprintf(buf, n, "%d", u);
        return;
    }
    if (key >= 0 && is_proxy(key)) {
        const int r = proxy_target(w, key);
        if (r < 0) std::snprintf(buf, n, "--");
        else display_key(w, r, buf, n);
        return;
    }
    display_key(w, idx, buf, n);
}

static intptr_t dispatcher(AEffect *e, int32_t op, int32_t idx, intptr_t v, void *p, float o) {
    Plugin *w = (Plugin *)e->object;
    if (op != effClose) flush_pend0(w);
    switch (op) {
    case effOpen: return 1;
    case effClose: delete w; return 1;
    case effSetProgram:
        if (v >= 0 && v < NSLOTS) {
            w->cur.store((int)v);
            slot_load(w);
            w->need_update.store(true);
        }
        return 0;
    case effGetProgram: return w->cur.load();
    case effGetProgramName: if (p) copy_str(p, slot_title(clampi(w->cur.load(), 0, NSLOTS - 1)).c_str(), 24); return 0;
    case effGetProgramNameIndexed:
        if (idx < 0 || idx >= NSLOTS || !p) return 0;
        copy_str(p, slot_title(idx).c_str(), 24);
        return 1;
    case effSetProgramName: {   /* only a saved slot has a line in the file to carry the name */
        const int n = clampi(w->cur.load(), 0, NSLOTS - 1);
        std::lock_guard<std::mutex> lk(g_bank_lock);
        if (!p || g_slot_chunk[n].empty()) return 0;
        std::string nm((const char *)p);
        for (char &c : nm) if (c == '\t' || c == '\n' || c == '\r') c = ' ';
        g_slot_name[n] = nm.substr(0, 23);
        bank_write_locked();
        return 0;
    }
    case effGetPlugCategory: return 2;   /* kPlugCategSynth */
    case effGetEffectName:
    case effGetProductString: copy_str(p, PLUG_NAME, 32); return 1;
    case effGetVendorString: copy_str(p, PLUG_VENDOR, 32); return 1;
    case effGetVendorVersion: return PLUG_VERSION;
    case effGetVstVersion: return 2400;
    case effCanBeAutomated: return idx >= 0 && idx < NPARAMS && !is_bank_key(idx) && !is_ui_key(idx);
    case effGetParamName: if (idx >= 0 && idx < NPARAMS) copy_str(p, PARAMS[idx].name, 32); return 1;
    case effGetParamLabel: if (idx >= 0 && idx < NPARAMS) copy_str(p, PARAMS[idx].unit, 8); return 1;
    case effGetParamDisplay: {
        if (idx < 0 || idx >= NPARAMS) return 0;
        char buf[48];
        display(w, idx, buf, sizeof buf);
        copy_str(p, buf, 24);
        return 1;
    }
    case effSetSampleRate:
        if (o > 0) { w->sr = o; w->engine.init(o); w->dirty.store(true); }
        return 1;
    case effSetBlockSize: return 1;
    case effMainsChanged: if (!v) w->engine.all_off(); return 1;
    case effProcessEvents: return process_events(w, (const VstEvents *)p);
    case effCanDo:
        if (p && (!std::strcmp((const char *)p, "receiveVstEvents") || !std::strcmp((const char *)p, "receiveVstMidiEvent") || !std::strcmp((const char *)p, "receiveVstTimeInfo"))) return 1;
        return -1;
    case effGetChunk: return get_chunk(w, (void **)p);
    case effSetChunk: return set_chunk(w, p, v);
    default: return 0;
    }
}

extern "C" __attribute__((visibility("default"))) AEffect *VSTPluginMain(audioMasterCallback master) {
    static std::once_flag once;
    std::call_once(once, [] {
        for (int i = 0; i < NPARAMS; i++) KEY_OF[i] = -1;
        for (int k = 0; k < NKEYS; k++) { IDX[k] = param_index(KEYS[k]); if (IDX[k] >= 0) KEY_OF[IDX[k]] = k; }
    });
    { std::lock_guard<std::mutex> lk(g_bank_lock); bank_load_locked(); }
    Plugin *w = new Plugin();
    w->master = master;
    for (int i = 0; i < NPARAMS; i++) { w->cache[i].store(PARAMS[i].def); w->notify[i].store(0); w->last_pos[i] = -1; }
    start_values(w);
    ui_defaults(w);
    static std::once_flag once_def;
    std::call_once(once_def, [w] { for (int i = 0; i < NPARAMS; i++) g_def[i] = w->cache[i].load(); g_def_ok = true; });
    for (int i = 0; i < NPARAMS; i++) w->notify[i].store(0);
    w->engine.init(w->sr);
    AEffect *e = &w->fx;
    std::memset(e, 0, sizeof *e);
    e->magic = 0x56737450;
    e->dispatcher = dispatcher;
    e->setParameter = setParameter;
    e->getParameter = getParameter;
    e->processReplacing = processReplacing;
    e->numParams = NPARAMS;
    e->numPrograms = NSLOTS;
    e->numInputs = 0;
    e->numOutputs = 2;
    e->flags = effFlagsCanReplacing | effFlagsProgramChunks | effFlagsIsSynth;
    e->uniqueID = PLUG_UID;
    e->version = PLUG_VERSION;
    e->object = w;
    return e;
}
