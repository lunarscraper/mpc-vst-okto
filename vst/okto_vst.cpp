static int param_index(const char *key) {
    for (int i = 0; i < NPARAMS; i++) if (!std::strcmp(PARAMS[i].key, key)) return i;
    return -1;
}
static float clamp01(float v) { return v < 0 ? 0 : v > 1 ? 1 : v; }
static int clampi(int v, int lo, int hi) { return v < lo ? lo : v > hi ? hi : v; }
static void copy_str(void *dst, const char *s, size_t max) {
    std::strncpy((char *)dst, s, max - 1);
    ((char *)dst)[max - 1] = 0;
}
static int norm_to_ui(const param_t *p, float n) {
    if (p->nopts) return (int)std::lround(clamp01(n) * (p->nopts - 1));
    return (int)std::lround(p->min + (p->max - p->min) * clamp01(n));
}
static float ui_to_norm(const param_t *p, double v) {
    if (p->nopts) return p->nopts > 1 ? clamp01((float)(v / (p->nopts - 1))) : 0.0f;
    return p->max > p->min ? clamp01((float)((v - p->min) / (p->max - p->min))) : 0.0f;
}
/* a knob at full resolution (the integer range only names its ends), a switch as its index */
static float val_norm(const param_t *p, float n) {
    if (p->nopts) return (float)norm_to_ui(p, n);
    return p->min + (p->max - p->min) * clamp01(n);
}
static float val_at(Plugin *w, int i) { return val_norm(&PARAMS[i], w->cache[i].load()); }
static float val(Plugin *w, int k) { return IDX[k] < 0 ? 0.0f : val_at(w, IDX[k]); }
static int ival(Plugin *w, int k) { return (int)std::lround(val(w, k)); }
static void set_val(Plugin *w, int i, double v) {
    if (i < 0) return;
    w->cache[i].store(ui_to_norm(&PARAMS[i], v));
    w->notify[i].store(1);
}

/* Where a stepped param (an option list) lands, in steps (same rule as mpc-vst-plugins' wrapper, settle()):
 * a value on a step is a click, a preset or automation; one between steps is a Q-Link, data wheel or drag move,
 * rounded toward the way it is moving - from the host's last position during a sweep, else from the current value -
 * so a turn smaller than one step still moves one step and a sweep moves steadily. */
static float settle(float pos, float cur, float last) {
    if (std::fabs(pos - std::round(pos)) <= 0.001f) return std::round(pos);
    const float dir = (last >= 0 && std::fabs(pos - last) < 0.5f) ? pos - last : pos - cur;
    if (dir == 0) return std::round(cur);
    return dir > 0 ? std::ceil(pos - 0.001f) : std::floor(pos + 0.001f);
}

/* the parameter an edit knob stands for right now (EDIT = OP 1..8 or PITCH), -1 = none */
static int proxy_target(Plugin *w, int k) {
    const int sel = clampi(ival(w, K_SEL), 0, 8);
    if (k >= X_OP0 && k < X_FROM0) return sel < 8 ? IDX[OPK(sel, k - X_OP0)] : -1;
    if (k >= X_FROM0 && k < X_ENV0) return sel < 8 ? IDX[MATK(k - X_FROM0, sel)] : -1;
    if (k >= X_ENV0 && k < G0) return sel < 8 ? IDX[OPK(sel, NOPF + k - X_ENV0)] : IDX[PEK(k - X_ENV0)];
    return -1;
}
/* what the host should read for parameter i */
static float norm_of(Plugin *w, int i) {
    const int k = KEY_OF[i];
    if (k == K_SLOT) return (float)w->cur.load() / 31;
    if (k >= 0 && is_trigger(k)) return 0.0f;
    if (popup_is(i)) return w->open[i];
    if (k >= 0 && is_proxy(k)) { const int r = proxy_target(w, k); return r < 0 ? 0.0f : w->cache[r].load(); }
    return w->cache[i].load();
}

struct NoDenormals {
#if defined(__arm__) && defined(__ARM_FP)
    uint32_t old = 0;
    NoDenormals() { asm volatile("vmrs %0, fpscr" : "=r"(old)); asm volatile("vmsr fpscr, %0" : : "r"(old | (1u << 24))); }
    ~NoDenormals() { asm volatile("vmsr fpscr, %0" : : "r"(old)); }
#elif defined(__aarch64__)
    uint64_t old = 0;
    NoDenormals() { asm volatile("mrs %0, fpcr" : "=r"(old)); asm volatile("msr fpcr, %0" : : "r"(old | (1ull << 24))); }
    ~NoDenormals() { asm volatile("msr fpcr, %0" : : "r"(old)); }
#elif defined(__x86_64__) || defined(__i386__)
    unsigned old = __builtin_ia32_stmxcsr();
    NoDenormals() { __builtin_ia32_ldmxcsr(old | 0x8040); }
    ~NoDenormals() { __builtin_ia32_ldmxcsr(old); }
#endif
};

/* ---- knob laws (tools/gen_okto.py has the inverse ones) ------------------- */
static float sq(float x) { return x * x; }
static float law_time(float x) { return x <= 0 ? 0.0f : 0.001f * std::pow(20000.0f, x); }      /* 1 ms .. 20 s */
static float law_level(float x) { return x <= 0 ? 0.0f : 0.005f * std::pow(3200.0f, x); }     /* libfmsynth: 0.005 .. 16 */
static float law_offset(float x) { return 4000.0f * x * x * x; }                               /* -1..1 -> +-4 kHz */
static float law_pm(float x) { return 0.06f * x * x; }                                         /* LFO -> pitch: up to ~1 st */
static float law_lfo(float x) { return 0.05f * std::pow(1280.0f, x); }                         /* 0.05 .. 64 Hz */
static float law_glide(float x) { return x <= 0 ? 0.0f : 0.002f * std::pow(1000.0f, x); }     /* 2 ms .. 2 s */
static float law_scale(float x) { return std::pow(4.0f, x); }                                  /* -1..1 -> x0.25 .. x4 */
static float ratio_of(int coarse, float fine) { return coarse <= 0 ? 0.0f : (coarse == 1 ? 0.5f : coarse - 1.0f) + fine * 0.01f; }
static const double ESYNC_BEATS[10] = {0, 0.125, 1.0 / 6, 0.25, 1.0 / 3, 0.5, 2.0 / 3, 1, 2, 4};
static const char *const ESYNC_NAME[10] = {"FREE", "1/32", "1/16T", "1/16", "1/8T", "1/8", "1/4T", "1/4", "1/2", "1/1"};
static const double LSYNC_BEATS[11] = {0, 16, 8, 4, 2, 1, 0.5, 0.25, 2.0 / 3, 1.0 / 3, 1.0 / 6};
static int units_of(float t) { return clampi(1 + (int)std::lround(t * 0.15f), 1, 16); }       /* T 0..100 -> 1..16 divisions */

static void env_from(Plugin *w, int base, okto::EnvP &e, bool bipolar) {
    /* base: the key of the envelope's E_EMODE */
    e.mode = clampi(ival(w, base + E_EMODE), 0, okto::NEMODES - 1);
    e.npts = clampi(ival(w, base + E_EPTS) + 1, 1, okto::NPTS);
    e.loop = clampi(ival(w, base + E_ELOOP), 0, okto::NPTS - 1);
    e.sync_beats = ESYNC_BEATS[clampi(ival(w, base + E_ESYNC), 0, 9)];
    e.rel = law_time(val(w, base + E_EREL) * 0.01f);
    for (int i = 0; i < okto::NPTS; i++) {
        const float l = val(w, base + E_L1 + i) * 0.01f;
        e.lvl[i] = bipolar ? okto::clampf(l, -1, 1) : okto::clampf(l, 0, 1);
        const float t = val(w, base + E_T1 + i);
        e.sec[i] = law_time(t * 0.01f);
        e.units[i] = units_of(t);
    }
}

static void configure(Plugin *w) {
    okto::Patch &p = w->patch;
    for (int o = 0; o < 8; o++) {
        p.wave[o] = clampi(ival(w, OPK(o, F_WAVE)), 0, okto::NWAVES - 1);
        p.ratio[o] = ratio_of(ival(w, OPK(o, F_COARSE)), val(w, OPK(o, F_FINE)));
        p.offset[o] = law_offset(val(w, OPK(o, F_OFFSET)) * 0.01f);
        p.amp[o] = law_level(val(w, OPK(o, F_LEVEL)) * 0.01f);
        p.out[o] = sq(val(w, OPK(o, F_OUT)) * 0.01f);
        p.pan[o] = val(w, OPK(o, F_PAN)) * 0.01f;
        p.vel[o] = val(w, OPK(o, F_VEL)) * 0.01f;
        p.kslo[o] = val(w, OPK(o, F_KSLO)) * 0.02f;
        p.kshi[o] = val(w, OPK(o, F_KSHI)) * 0.02f;
        p.am[o] = val(w, OPK(o, F_AM)) * 0.01f;
        p.pm[o] = law_pm(val(w, OPK(o, F_PM)) * 0.01f);
        p.penv[o] = val(w, OPK(o, F_PENV)) * 0.01f;
        p.wheel[o] = val(w, OPK(o, F_WHEEL)) * 0.01f;
        env_from(w, OPK(o, NOPF), p.env[o], false);
        for (int d = 0; d < 8; d++) p.mod[o][d] = sq(val(w, MATK(o, d)) * 0.01f);
    }
    env_from(w, PEK(0), p.pe, true);
    p.pe_depth = val(w, G_PE_DEPTH);
    p.volume = 0.8f * sq(val(w, G_VOLUME) * 0.01f);
    p.bright = val(w, G_BRIGHT) * 0.01f;
    p.feedback = val(w, G_FEEDBACK) * 0.01f;
    p.env_time = law_scale(val(w, G_ENV_TIME) * 0.01f);
    p.rel_scale = law_scale(val(w, G_REL_SCALE) * 0.01f);
    p.lfo_hz = law_lfo(val(w, G_LFO_RATE) * 0.01f);
    p.lfo_wave = clampi(ival(w, G_LFO_WAVE), 0, okto::NLFOW - 1);
    p.lfo_beats = LSYNC_BEATS[clampi(ival(w, G_LFO_SYNC), 0, 10)];
    p.lfo_delay = 5.0f * sq(val(w, G_LFO_DELAY) * 0.01f);
    p.lfo_key = ival(w, G_LFO_KEY) == 1;
    p.vibrato = law_pm(val(w, G_VIBRATO) * 0.01f);
    p.mw_vib = law_pm(val(w, G_MW_VIB) * 0.01f);
    p.mw_bright = val(w, G_MW_BRIGHT) * 0.01f;
    p.vmode = clampi(ival(w, G_VMODE), 0, 2);
    p.voices = clampi(ival(w, G_VOICES) + 1, 1, okto::MAXV);
    p.glide = law_glide(val(w, G_GLIDE) * 0.01f);
    p.unison = clampi(ival(w, G_UNISON) + 1, 1, 3);
    p.detune = val(w, G_DETUNE);
    p.width = val(w, G_WIDTH) * 0.01f;
    p.transpose = (float)(ival(w, G_TRANSPOSE) - 24);
    p.bend_range = (float)clampi(ival(w, G_BEND), 0, 12);
    if (p.vmode != w->last_vmode || p.unison != w->last_unison) {   /* voices of the old layout would hang */
        if (w->last_vmode >= 0) w->engine.all_off();
        w->last_vmode = p.vmode; w->last_unison = p.unison;
    }
    w->engine.set_patch(p);
}

/* the start patch (gen_okto.py: a sine on OP 1 with libfmsynth's default envelope) */
static void start_values(Plugin *w) {
    for (const KV &kv : START) {
        const int i = param_index(kv.key);
        if (i >= 0 && KEY_OF[i] != K_SEL) set_val(w, i, kv.v);
    }
}
static void ui_defaults(Plugin *w) { set_val(w, IDX[K_SEL], 0); }

/* ---- state as text: "key=value;" for every sound parameter that differs from its start value.
 * Used for the project chunk and the preset slots alike; restored by key on top of the start
 * values, so parameters added later keep old projects and presets loading. The chunk also
 * carries EDIT (with_ui), a preset slot doesn't. ------------------------------------------------ */
static std::string build_state(Plugin *w, bool with_ui) {
    std::string t;
    char buf[96];
    for (int i = 0; i < NPARAMS; i++) {
        if (is_bank_key(i) || (!with_ui && is_ui_key(i))) continue;
        const float n = w->cache[i].load();
        if (g_def_ok && std::fabs(n - g_def[i]) < 1e-7f) continue;
        std::snprintf(buf, sizeof buf, "%s=%.3f;", PARAMS[i].key, (double)val_at(w, i));
        t += buf;
    }
    return t;
}
static void apply_state(Plugin *w, const std::string &t, bool with_slot) {
    for (size_t pos = 0; pos < t.size();) {
        size_t semi = t.find(';', pos);
        if (semi == std::string::npos) break;
        std::string kv = t.substr(pos, semi - pos);
        pos = semi + 1;
        size_t eq = kv.find('=');
        if (eq == std::string::npos) continue;
        const std::string key = kv.substr(0, eq);
        if (key == "prog") {
            const int v = std::atoi(kv.c_str() + eq + 1);
            if (with_slot && v >= 0 && v < 32) w->cur.store(v);
            continue;
        }
        const int i = param_index(key.c_str());
        if (i >= 0 && !is_bank_key(i) && (with_slot || !is_ui_key(i))) set_val(w, i, std::atof(kv.c_str() + eq + 1));
    }
    for (int k = X_OP0; k < G0; k++) if (IDX[k] >= 0) w->notify[IDX[k]].store(1);   /* the edit knobs follow */
    w->dirty.store(true);
}

/* ---------------------------------------------------------------------------
 * Preset bank (pattern of mpc-vst-acid / mpc-vst-rattler): 32 slots shared by every Okto
 * instance and every project, kept in one text file on the SD card (one line per saved slot:
 * "index<TAB>name<TAB>state"). The slots are also the plugin's VST programs, so the host's
 * PRESET list shows and selects them; the PRESET knob + LOAD/SAVE buttons on the PRESET tab do
 * the same from the skin. The slots come with factory sounds until SAVE overwrites them.
 * ------------------------------------------------------------------------- */
#define NSLOTS 32
static std::mutex g_bank_lock;
static bool g_bank_loaded;
static std::string g_slot_chunk[NSLOTS], g_slot_name[NSLOTS], g_bank_path;
enum { NFACTORY = (int)(sizeof FACTORY / sizeof FACTORY[0]) };
static_assert(NFACTORY <= NSLOTS, "more factory sounds than slots");

static std::string so_dir() {
    std::string dir;
    if (FILE *f = std::fopen("/proc/self/maps", "r")) {
        char line[1024];
        while (std::fgets(line, sizeof line, f)) {
            char *p = std::strstr(line, "/okto.so");
            char *first = std::strchr(line, '/');
            if (!p || !first || first > p) continue;
            dir.assign(first, (size_t)(p - first));
            break;
        }
        std::fclose(f);
    }
    return dir;
}
static void bank_load_locked() {
    if (g_bank_loaded) return;
    g_bank_loaded = true;
    g_bank_path.clear();
    if (const char *env = std::getenv("OKTO_PRESETS")) g_bank_path = env;
    else {
        std::string dir = so_dir(), cand[2];
        if (dir.empty()) dir = "/tmp";
        size_t cut = dir.rfind('/');
        cand[0] = (cut != std::string::npos && cut > 0 ? dir.substr(0, cut) : dir) + "/okto_presets.txt";
        cand[1] = dir + "/okto_presets.txt";
        for (const std::string &c : cand)
            if (FILE *f = std::fopen(c.c_str(), "r")) { std::fclose(f); g_bank_path = c; break; }
        for (int i = 0; i < 2 && g_bank_path.empty(); i++)
            if (FILE *f = std::fopen(cand[i].c_str(), "a")) { std::fclose(f); g_bank_path = cand[i]; }
    }
    if (g_bank_path.empty()) return;
    if (FILE *f = std::fopen(g_bank_path.c_str(), "r")) {
        static char line[65536];
        while (std::fgets(line, sizeof line, f)) {
            line[std::strcspn(line, "\r\n")] = 0;
            char *t1 = std::strchr(line, '\t');
            char *t2 = t1 ? std::strchr(t1 + 1, '\t') : nullptr;
            int idx = std::atoi(line);
            if (!t2 || idx < 1 || idx > NSLOTS) continue;
            *t1 = *t2 = 0;
            g_slot_name[idx - 1] = t1 + 1;
            g_slot_chunk[idx - 1] = t2 + 1;
        }
        std::fclose(f);
    }
}
static bool bank_write_locked() {   /* whole file, via a temp file so a power cut can't leave half a bank */
    if (g_bank_path.empty()) return false;
    std::string tmp = g_bank_path + ".tmp";
    FILE *f = std::fopen(tmp.c_str(), "w");
    if (!f) return false;
    for (int i = 0; i < NSLOTS; i++)
        if (!g_slot_chunk[i].empty())
            std::fprintf(f, "%d\t%s\t%s\n", i + 1, g_slot_name[i].c_str(), g_slot_chunk[i].c_str());
    return std::fclose(f) == 0 && std::rename(tmp.c_str(), g_bank_path.c_str()) == 0;
}
static std::string slot_title(int i) {
    std::lock_guard<std::mutex> lk(g_bank_lock);
    char buf[32];
    if (g_slot_chunk[i].empty()) {
        if (i < NFACTORY) return FACTORY[i].name;
        std::snprintf(buf, sizeof buf, "%02d (empty)", i + 1);
        return buf;
    }
    if (!g_slot_name[i].empty()) return g_slot_name[i];
    std::snprintf(buf, sizeof buf, "Okto %02d", i + 1);
    return buf;
}
static void slot_load(Plugin *w) {
    const int n = clampi(w->cur.load(), 0, NSLOTS - 1);
    std::string c;
    { std::lock_guard<std::mutex> lk(g_bank_lock); c = g_slot_chunk[n]; }
    if (c.empty() && n < NFACTORY) c = FACTORY[n].state;
    else if (c.empty()) return;          /* an empty slot leaves the current sound alone */
    start_values(w);
    apply_state(w, c, false);
}
static bool slot_save(Plugin *w) {
    const int n = clampi(w->cur.load(), 0, NSLOTS - 1);
    std::string c = build_state(w, false);
    if (c.empty()) c = ";";              /* the plain start sound is a sound too */
    std::lock_guard<std::mutex> lk(g_bank_lock);
    g_slot_chunk[n] = c;
    return bank_write_locked();
}

